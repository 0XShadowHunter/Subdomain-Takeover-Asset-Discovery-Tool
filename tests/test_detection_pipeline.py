def test_load_phase2_valid(tmp_path):
    path = _write_phase2(tmp_path, [_github_record()])
    result = load_phase2_file(path)
    assert result.target == "example.com"
    assert len(result.records) == 1


def test_load_phase2_errors(tmp_path):
    with pytest.raises(Phase3InputError):
        load_phase2_file(tmp_path / "missing.json")
    bad = tmp_path / "bad.json"
    bad.write_text("nope{", encoding="utf-8")
    with pytest.raises(Phase3InputError):
        load_phase2_file(bad)
    wrong = tmp_path / "wrong.json"
    wrong.write_text(json.dumps({"hello": 1}), encoding="utf-8")
    with pytest.raises(Phase3InputError):
        load_phase2_file(wrong)


def test_run_detection_finds_and_skips(tmp_path):
    path = _write_phase2(
        tmp_path, [_github_record(), _dangling_record(), _dead_record(), _cloudfront_record()]
    )
    # recheck_dns=False → no live DNS anywhere in this test
    result = run_detection(path, settings={}, recheck_dns=False)

    assert result.target == "example.com"
    types = {f.type for f in result.findings}
    assert types == {"CNAME_FINGERPRINT", "CNAME_NXDOMAIN"}  # dead + cloudfront clean

    by_sub = {f.subdomain: f for f in result.findings}
    assert by_sub["blog.example.com"].service == "GitHub Pages"
    assert by_sub["blog.example.com"].confidence == "HIGH"
    assert by_sub["lost.example.com"].type == "CNAME_NXDOMAIN"

    # Contract summary shape (AGENT_PLAN.md §2)
    assert result.summary["total_scanned"] == 4
    assert result.summary["vulnerable"] == 1  # the GitHub Pages HIGH finding
    assert result.summary["by_confidence"]["MEDIUM"] == 1
    assert result.generated_at


def test_run_detection_empty_records(tmp_path):
    path = _write_phase2(tmp_path, [])
    result = run_detection(path, settings={}, recheck_dns=False)
    assert result.findings == []
    assert result.summary == {
        "total_scanned": 0,
        "vulnerable": 0,
        "by_confidence": {"HIGH": 0, "MEDIUM": 0, "LOW": 0},
    }


def test_run_detection_skips_invalid_record_names(tmp_path):
    path = tmp_path / "phase2.json"
    path.write_text(
        json.dumps(
            {
                "target": "example.com",
                "generated_at": "now",
                "records": [_github_record(), {"name": "bad name!", "resolved": False}],
            }
        ),
        encoding="utf-8",
    )
    result = run_detection(path, settings={}, recheck_dns=False)
    assert result.summary["total_scanned"] == 1
